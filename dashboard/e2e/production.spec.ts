test("forced synthetic password change revokes the old session and requires login with the replacement", async ({ page, fixture }) => {
  await login(page, fixture, "password_change");
  await expect(page).toHaveURL(/\/password$/);
  const password = fixture.password + "-Changed";
  await page.getByLabel("Current / temporary password", { exact: true }).fill(fixture.password);
  await page.getByLabel("New password", { exact: true }).fill(password);
  await page.getByLabel("Confirm new password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Save password & sign in again", exact: true }).click();
  await expect(page).toHaveURL(/\/login\?passwordChanged=1$/);
  await page.goto("/contacts");
  await expect(page).toHaveURL(/\/login$/);
  await login(page, fixture, "password_change", password);
  await expect(page.getByRole("heading", { name: /Good (morning|afternoon|evening)/ })).toBeVisible();
});
